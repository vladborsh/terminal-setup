#!/usr/bin/env bash
set -euo pipefail

REPO_RAW="https://raw.githubusercontent.com/vladborsh/terminal-setup/main"
NVM_VERSION="v0.40.4"
CCSTATUSLINE_VERSION="2.2.19"

# === helpers ===
log()  { printf "\n\033[1;32m[INFO]\033[0m %s\n" "$*"; }
warn() { printf "\n\033[1;33m[WARN]\033[0m %s\n" "$*"; }

# Read from the terminal even when the script itself is piped into bash.
ask() {
  local prompt=$1 var=$2 reply=""
  if [[ -r /dev/tty ]]; then
    read -rp "$prompt" reply < /dev/tty || true
  fi
  printf -v "$var" '%s' "$reply"
}

backup() {
  [[ -e "$1" ]] && cp "$1" "$1.bak.$(date +%Y%m%d%H%M%S)"
  return 0
}

# Replace the block between markers (or append it) so re-runs stay idempotent.
write_block() {
  local file=$1 begin=$2 end=$3 content=$4
  touch "$file"
  if grep -qF "$begin" "$file"; then
    backup "$file"
    awk -v b="$begin" -v e="$end" '
      index($0, b) { skip = 1; next }
      skip && index($0, e) { skip = 0; next }
      !skip
    ' "$file" > "$file.tmp" && mv "$file.tmp" "$file"
  fi
  if [[ -s "$file" && -n "$(tail -n 1 "$file")" ]]; then
    echo >> "$file"
  fi
  printf '%s\n%s\n%s\n' "$begin" "$content" "$end" >> "$file"
}

# When piped (curl ... | bash), every command that reads stdin would eat the
# rest of the script. Re-run from a downloaded copy with stdin on the terminal.
if [[ ! -f "${BASH_SOURCE[0]:-}" ]]; then
  SELF="$(mktemp -t terminal-setup)"
  curl -fsSL "$REPO_RAW/setup.sh" -o "$SELF"
  exec bash "$SELF" < /dev/tty
fi

# Use repo files next to the script, or download them when they are missing.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
TMP_DIR="$(mktemp -d)"
trap 'rm -rf "$TMP_DIR"' EXIT

repo_file() {
  local rel=$1
  if [[ -f "$SCRIPT_DIR/$rel" ]]; then
    printf '%s' "$SCRIPT_DIR/$rel"
  else
    mkdir -p "$TMP_DIR/$(dirname "$rel")"
    curl -fsSL "$REPO_RAW/$rel" -o "$TMP_DIR/$rel"
    printf '%s' "$TMP_DIR/$rel"
  fi
}

if [[ "$OSTYPE" != "darwin"* ]]; then
  warn "This script is designed for macOS."
  exit 1
fi

# --- Homebrew ---
load_brew() {
  if [[ -x /opt/homebrew/bin/brew ]]; then
    eval "$(/opt/homebrew/bin/brew shellenv)"
  elif [[ -x /usr/local/bin/brew ]]; then
    eval "$(/usr/local/bin/brew shellenv)"
  fi
}

load_brew
if ! command -v brew >/dev/null 2>&1; then
  log "Homebrew not found. Installing..."
  /bin/bash -c "$(curl -fsSL https://raw.githubusercontent.com/Homebrew/install/HEAD/install.sh)"
  load_brew
else
  log "Homebrew already installed."
fi

BREW_BIN="$(command -v brew)"
write_block "$HOME/.zprofile" \
  "# ===== Homebrew (generated by setup.sh) =====" \
  "# ===== End Homebrew =====" \
  "eval \"\$($BREW_BIN shellenv)\""

# --- brew packages ---
log "Installing packages via Homebrew..."

brew update

# Casks fail if the app/font was installed outside Homebrew, so don't abort on them.
if ! brew list --cask ghostty &>/dev/null && [[ ! -d "/Applications/Ghostty.app" && ! -d "$HOME/Applications/Ghostty.app" ]]; then
  brew install --cask ghostty || warn "Could not install Ghostty."
fi
if ! brew list --cask font-meslo-lg-nerd-font &>/dev/null && ! ls "$HOME/Library/Fonts"/MesloLGSNerdFont* &>/dev/null; then
  brew install --cask font-meslo-lg-nerd-font || warn "Could not install Meslo Nerd Font."
fi

brew install tmux fzf ripgrep bat fd eza git python jq
brew install powerlevel10k
brew install zsh-autosuggestions zsh-syntax-highlighting zsh-history-substring-search

# --- Git global config ---
log "Configuring git..."
CURRENT_GIT_NAME=$(git config --global user.name 2>/dev/null || true)
CURRENT_GIT_EMAIL=$(git config --global user.email 2>/dev/null || true)

if [[ -z "$CURRENT_GIT_NAME" ]]; then
  ask "  Enter your git user name: " GIT_NAME
  [[ -n "$GIT_NAME" ]] && git config --global user.name "$GIT_NAME"
else
  log "Git user.name already set: $CURRENT_GIT_NAME"
fi

if [[ -z "$CURRENT_GIT_EMAIL" ]]; then
  ask "  Enter your git email: " GIT_EMAIL
  [[ -n "$GIT_EMAIL" ]] && git config --global user.email "$GIT_EMAIL"
else
  log "Git user.email already set: $CURRENT_GIT_EMAIL"
fi

git config --global init.defaultBranch main
git config --global credential.helper osxkeychain

# --- Ghostty config ---
log "Writing Ghostty config..."
mkdir -p "$HOME/.config/ghostty"
backup "$HOME/.config/ghostty/config"
cat > "$HOME/.config/ghostty/config" << 'EOF'
font-family = MesloLGS Nerd Font Mono
font-size = 13
theme = Catppuccin Mocha
EOF

# --- Oh My Zsh ---
# An existing ~/.zshrc stops the installer from writing its own template.
touch "$HOME/.zshrc"
if [[ ! -d "$HOME/.oh-my-zsh" ]]; then
  log "Installing Oh My Zsh..."
  RUNZSH=no CHSH=no KEEP_ZSHRC=yes \
  sh -c "$(curl -fsSL https://raw.githubusercontent.com/ohmyzsh/ohmyzsh/master/tools/install.sh)"
else
  log "Oh My Zsh already installed."
fi

ZSH_CUSTOM=${ZSH_CUSTOM:-$HOME/.oh-my-zsh/custom}

# --- fzf-tab (not in Homebrew, clone manually) ---
log "Installing fzf-tab plugin..."
if [[ ! -d "$ZSH_CUSTOM/plugins/fzf-tab" ]]; then
  git clone https://github.com/Aloxaf/fzf-tab "$ZSH_CUSTOM/plugins/fzf-tab"
fi

# --- NVM ---
export NVM_DIR="$HOME/.nvm"
if [[ ! -d "$NVM_DIR" ]]; then
  log "Installing NVM..."
  # PROFILE=/dev/null: ~/.zshrc gets NVM lines from the block below instead.
  curl -fsSL "https://raw.githubusercontent.com/nvm-sh/nvm/$NVM_VERSION/install.sh" | PROFILE=/dev/null bash
else
  log "NVM already installed."
fi

log "Installing Node.js LTS via NVM..."
# nvm is not compatible with `set -eu`.
set +eu
# shellcheck source=/dev/null
\. "$NVM_DIR/nvm.sh"
nvm install --lts
nvm alias default 'lts/*'
nvm use default >/dev/null
set -eu

# --- Claude Code ---
export PATH="$HOME/.local/bin:$PATH"
ask "  Install Claude Code and its config? [y/N] " INSTALL_CLAUDE
if [[ "$INSTALL_CLAUDE" =~ ^[Yy]$ ]]; then
  if ! command -v claude >/dev/null 2>&1; then
    log "Installing Claude Code (native installer)..."
    curl -fsSL https://claude.ai/install.sh | bash
  else
    log "Claude Code already installed: $(claude --version)"
  fi

  log "Installing ccstatusline..."
  npm install -g "ccstatusline@$CCSTATUSLINE_VERSION" || warn "Could not install ccstatusline."
  mkdir -p "$HOME/.config/ccstatusline"
  backup "$HOME/.config/ccstatusline/settings.json"
  cp "$(repo_file claude/ccstatusline.json)" "$HOME/.config/ccstatusline/settings.json"

  log "Merging Claude settings into ~/.claude/settings.json..."
  mkdir -p "$HOME/.claude"
  CLAUDE_SETTINGS="$HOME/.claude/settings.json"
  REPO_SETTINGS="$(repo_file claude/settings.json)"
  if [[ -s "$CLAUDE_SETTINGS" ]]; then
    backup "$CLAUDE_SETTINGS"
    if jq -s '.[0] * .[1]' "$CLAUDE_SETTINGS" "$REPO_SETTINGS" > "$CLAUDE_SETTINGS.tmp"; then
      mv "$CLAUDE_SETTINGS.tmp" "$CLAUDE_SETTINGS"
    else
      rm -f "$CLAUDE_SETTINGS.tmp"
      warn "~/.claude/settings.json is not valid JSON; left unchanged. Merge $REPO_SETTINGS manually."
    fi
  else
    cp "$REPO_SETTINGS" "$CLAUDE_SETTINGS"
  fi

  log "Installing Claude plugins..."
  claude plugin marketplace add nextlevelbuilder/ui-ux-pro-max-skill \
    || warn "Could not add marketplace ui-ux-pro-max-skill."
  claude plugin install ui-ux-pro-max@ui-ux-pro-max-skill \
    || warn "Could not install plugin ui-ux-pro-max. Run inside claude: /plugin"

  log "Installing agent skills..."
  npx -y skills add mattpocock/skills -g -a claude-code -y \
    --skill grill-me --skill grill-with-docs --skill grilling \
    --skill to-questionnaire --skill wait-what \
    || warn "Could not install mattpocock/skills."
  npx -y skills add vercel-labs/skills -g -a claude-code -y --skill find-skills \
    || warn "Could not install vercel-labs/skills."

  ask "  Install Orca skills (orca-cli, orchestration, computer-use)? [y/N] " INSTALL_ORCA
  if [[ "$INSTALL_ORCA" =~ ^[Yy]$ ]]; then
    npx -y skills add stablyai/orca -g -a claude-code -y \
      --skill orca-cli --skill orchestration --skill computer-use \
      || warn "Could not install stablyai/orca skills."
  fi

  log "Claude Code ready. Run 'claude' to log in."
else
  log "Skipping Claude Code installation."
fi

# --- .zshrc ---
log "Updating ~/.zshrc..."

write_block "$HOME/.zshrc" \
  "# ===== Custom terminal setup (generated by setup.sh) =====" \
  "# ===== End custom terminal setup =====" \
  "$(cat << 'EOF'
# Homebrew (also set in ~/.zprofile; repeated for non-login shells)
if [[ -x /opt/homebrew/bin/brew ]]; then
  eval "$(/opt/homebrew/bin/brew shellenv)"
elif [[ -x /usr/local/bin/brew ]]; then
  eval "$(/usr/local/bin/brew shellenv)"
fi
BREW_PREFIX="$(brew --prefix)"

export PATH="$HOME/.local/bin:$PATH"

export ZSH="$HOME/.oh-my-zsh"
ZSH_THEME=""  # Powerlevel10k is sourced below
plugins=(git)
source "$ZSH/oh-my-zsh.sh"

# Powerlevel10k
source "$BREW_PREFIX/share/powerlevel10k/powerlevel10k.zsh-theme"

# fzf-tab must load after compinit and before widget-wrapping plugins
source "${ZSH_CUSTOM:-$ZSH/custom}/plugins/fzf-tab/fzf-tab.plugin.zsh"

# fzf key bindings and completion
source <(fzf --zsh)

# Plugins (from Homebrew); syntax-highlighting goes after autosuggestions
source "$BREW_PREFIX/share/zsh-autosuggestions/zsh-autosuggestions.zsh"
source "$BREW_PREFIX/share/zsh-syntax-highlighting/zsh-syntax-highlighting.zsh"
source "$BREW_PREFIX/share/zsh-history-substring-search/zsh-history-substring-search.zsh"
bindkey '^[[A' history-substring-search-up
bindkey '^[[B' history-substring-search-down

# NVM
export NVM_DIR="$HOME/.nvm"
[ -s "$NVM_DIR/nvm.sh" ] && \. "$NVM_DIR/nvm.sh"
[ -s "$NVM_DIR/bash_completion" ] && \. "$NVM_DIR/bash_completion"

# Aliases
alias python='python3'
alias cat='bat'
alias ls='eza'
alias ll='eza -l'
alias la='eza -la'

# Powerlevel10k config (run `p10k configure` to generate)
[[ ! -f ~/.p10k.zsh ]] || source ~/.p10k.zsh
EOF
)"

# --- tmux.conf ---
log "Writing ~/.tmux.conf..."
backup "$HOME/.tmux.conf"
cat > "$HOME/.tmux.conf" << 'EOF'
setw -g mode-keys vi
set -g mouse on
EOF

log "Done! Next steps:"
echo "  1) Open Ghostty — Meslo Nerd Font and Catppuccin Mocha are set in ~/.config/ghostty/config."
echo "  2) Restart the terminal; the Powerlevel10k wizard starts automatically (or run: p10k configure)."
echo "  3) Run 'claude' to log in to Claude Code."
echo "  4) Start tmux with: tmux"
